// Package supervisor manages routerd's child workers. It is the sole owner of
// process creation and wait/reaping in its process: callers must not concurrently
// launch and wait for unrelated children with os/exec.
package supervisor

import (
	"context"
	"time"

	"github.com/imksoo/routerd2/internal/configref"
	"github.com/imksoo/routerd2/internal/release"
)

const SocketName = "supervisor.sock"

// PowerAction is performed by the appliance entrypoint after all workers exit.
type PowerAction string

const (
	PowerOff PowerAction = "poweroff"
	Reboot   PowerAction = "reboot"
)

type PowerRequest struct {
	Action PowerAction `json:"action"`
}

type RestartPolicy string

const (
	RestartAlways    RestartPolicy = "always"
	RestartOnFailure RestartPolicy = "on-failure"
	RestartNever     RestartPolicy = "never"
)

type Spec struct {
	Name             string
	Role             string
	Args             []string
	Required         bool
	Restart          RestartPolicy
	StartupTimeout   time.Duration
	HeartbeatTimeout time.Duration
	StopTimeout      time.Duration
	BackoffMin       time.Duration
	BackoffMax       time.Duration
}

type Options struct {
	// OnShutdown stops entrypoint-owned readiness monitoring before workers drain.
	OnShutdown context.CancelFunc

	ReleaseAuthority *release.Authority
	authorityJSON    string // canonical, reserved, control-only release selection
	Startup          *configref.Selection
	startupJSON      string            // validated copy for control only, reserved against inherited env
	instanceID       string            // generated by Run; never selected by a caller or config
	Executables      map[string]string // fixed role -> executable catalog, resolved once by Run
	Engines          map[string]string // fixed role -> engine archive, pinned with the executable catalog
	ReleaseID        string
	RuntimeDir       string
	StateDir         string
	ConfigPath       string
	Platform         string
	Modules          []Spec
	// DynamicRoles is the allowlist of bundled protocol workers that the
	// control service can instantiate. Core workers cannot be replaced by IPC.
	DynamicRoles []string
	// Env overrides inherited environment entries for all workers.
	Env []string
}

type Status struct {
	InstanceID string         `json:"instance_id"`
	ReleaseID  string         `json:"release_id"`
	Platform   string         `json:"platform"`
	PID        int            `json:"pid"`
	StartedAt  time.Time      `json:"started_at"`
	Ready      bool           `json:"ready"`
	Stopping   bool           `json:"stopping"`
	Modules    []ModuleStatus `json:"modules"`
}

type ModuleStatus struct {
	Name          string      `json:"name"`
	Role          string      `json:"role"`
	State         string      `json:"state"`
	Required      bool        `json:"required"`
	PID           int         `json:"pid,omitempty"`
	ReleaseID     string      `json:"release_id,omitempty"`
	Ready         bool        `json:"ready"`
	Generation    uint64      `json:"generation"`
	Restarts      uint64      `json:"restarts"`
	StartedAt     *time.Time  `json:"started_at,omitempty"`
	LastHeartbeat *time.Time  `json:"last_heartbeat,omitempty"`
	LastExit      *ExitStatus `json:"last_exit,omitempty"`
	LastError     string      `json:"last_error,omitempty"`
	ConfigDigest  string      `json:"config_digest,omitempty"`
}

type DynamicModule struct {
	Name         string `json:"name"`
	Role         string `json:"role"`
	ConfigDigest string `json:"config_digest"`
}

// ReconcileModules replaces only the dynamic module set. Each configuration
// lives at RuntimeDir/instances/NAME/DIGEST.json, mode 0600, and is verified by
// the child before decoding. Neither arbitrary executable paths nor argv can
// cross this management API.
type ReconcileModules struct {
	Modules []DynamicModule `json:"modules"`
}

type ExitStatus struct {
	At     time.Time `json:"at"`
	Code   int       `json:"code"`
	Signal string    `json:"signal,omitempty"`
}
